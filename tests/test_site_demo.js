// Browser QA facoltativa: npm install --prefix /tmp/hpx-site-qa playwright
// Avviare una preview statica e impostare HPX_DEMO_URL; Playwright resta fuori dal progetto.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const {chromium} = require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const productionRequests=[];
    const tileRequests=[];
    page.on('request',request=>{if(/:(8000|8080)\//.test(request.url()))productionRequests.push(request.url());});
    page.on('request',request=>{if(/tile\.openstreetmap\.org|basemaps\.cartocdn\.com/.test(request.url()))tileRequests.push(request.url());});
    await page.goto(process.env.HPX_DEMO_URL||'http://127.0.0.1:8765/',{waitUntil:'networkidle'});
    const protocolFaq=page.locator('.faq-item').filter({hasText:'Quali protocolli e attacchi vengono monitorati?'});
    await protocolFaq.locator('button').click();
    assert.match(await protocolFaq.locator('.faq-a').textContent(),/MySQL.*SCADA.*Modbus\/TCP.*S7comm/);
    for(const width of [320,390,768,1024,1440]){
      await page.setViewportSize({width,height:1000});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Overflow home a ${width}px`);
      assert.ok(await protocolFaq.locator('.faq-a').evaluate(el=>el.scrollHeight<=el.clientHeight+1),'La FAQ non deve essere tagliata');
    }
    assert.match(await page.locator('#metrics').textContent(),/5.*Servizi honeypot/s);
    assert.doesNotMatch(await page.locator('body').textContent(),/\bSMB\b|NTLM/i);
    console.log('OK FAQ aggiornata e leggibile su desktop/mobile, conteggio servizi coerente');
    await page.evaluate(()=>navigateTo('dashboard'));
    await page.waitForSelector('#panel-overview.active');
    assert.equal(await page.locator('#demo-total').textContent(),'11');
    assert.equal(await page.locator('#demo-high').textContent(),'5');
    assert.equal(await page.locator('#demo-countries').textContent(),'4');
    await page.waitForSelector('#demo-map .leaflet-overlay-pane svg path');
    assert.equal(await page.locator('#demo-map .leaflet-overlay-pane svg path').count(),5);
    assert.equal(await page.locator('#demo-map .demo-tile-pane').evaluate(el=>el.style.zIndex),'200');
    assert.ok(await page.locator('#demo-map .demo-tile-pane svg path').count()>0);
    assert.deepEqual(tileRequests,[]);
    assert.ok(await page.locator('.dash-page-nav [data-panel="events"]').isVisible());
    const ids=await page.locator('[id]').evaluateAll(elements=>elements.map(el=>el.id));
    assert.equal(new Set(ids).size,ids.length);
    console.log('OK panoramica, metriche, marker, navigazione e ID HTML');

    await page.selectOption('#demo-country','Local');
    assert.equal(await page.locator('#demo-total').textContent(),'2');
    assert.equal(await page.locator('#demo-map .leaflet-overlay-pane svg path').count(),1);
    await page.click('#demo-map .leaflet-overlay-pane svg path');
    await page.waitForSelector('.leaflet-popup-content');
    assert.match(await page.locator('.leaflet-popup-content').textContent(),/Dalmine/);
    await page.evaluate(()=>resetDemoFilters());
    await page.selectOption('#demo-danger','Alto');
    assert.equal(await page.locator('#demo-total').textContent(),'5');
    await page.evaluate(()=>switchPanel('events'));
    assert.equal(await page.locator('#demo-events tbody tr').count(),5);
    await page.selectOption('#demo-period','all');
    await page.selectOption('#demo-danger','all');
    assert.equal(await page.locator('#demo-events tbody tr').count(),12);
    await page.fill('#demo-search','T1110');
    assert.equal(await page.locator('#demo-events tbody tr').count(),2);
    await page.fill('#demo-search','nonexistent-example');
    assert.match(await page.locator('#demo-events').textContent(),/Nessun incidente/);
    await page.evaluate(()=>resetDemoFilters());
    console.log('OK filtri temporali, geografici, pericolo, ricerca MITRE e stato vuoto');

    await page.evaluate(()=>openDemoIncident(104));
    await page.waitForSelector('#demo-detail[open]');
    assert.match(await page.locator('#demo-detail').textContent(),/Command Injection/);
    assert.match(await page.locator('#demo-detail pre').first().textContent(),/wget/);
    await page.selectOption('#demo-detail-triage','authorized_activity');
    assert.equal(await page.locator('#demo-total').textContent(),'10');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#demo-detail').evaluate(el=>el.open),false);
    await page.selectOption('#demo-triage','triaged_out');
    assert.equal(await page.locator('#demo-events tbody tr').count(),1);
    await page.evaluate(()=>openDemoIP(104));
    assert.match(await page.locator('#demo-detail').textContent(),/4 incidenti nello scenario/);
    await page.evaluate(()=>closeDemoDetail());
    await page.evaluate(()=>resetDemoFilters());
    console.log('OK dettagli, evidenze, triage, storico IP e chiusura da tastiera');

    await page.evaluate(()=>switchPanel('timeline'));
    assert.ok(await page.locator('.demo-story').count()>0);
    assert.equal(await page.locator('.demo-story-head').first().evaluate(el=>getComputedStyle(el).alignItems),'center');
    assert.equal(await page.locator('.demo-story-head>.sev-badge').first().evaluate(el=>getComputedStyle(el).alignItems),'center');
    await page.evaluate(()=>switchPanel('sources'));
    assert.equal(await page.locator('#demo-source-cards .dash-card').count(),6);
    await page.evaluate(()=>switchPanel('thresholds'));
    assert.equal(await page.locator('#demo-filters').isVisible(),false);
    await page.fill('#threshold-login','2');
    await page.getByRole('button',{name:'Salva impostazioni demo',exact:true}).click();
    await page.getByRole('button',{name:'Simula tentativo fallito',exact:true}).click();
    assert.match(await page.locator('#demo-credential-status').textContent(),/1\/2/);
    await page.getByRole('button',{name:'Simula tentativo fallito',exact:true}).click();
    assert.match(await page.locator('#demo-credential-status').textContent(),/Incidente correlato/);
    assert.equal(await page.evaluate(()=>demoEvents.filter(e=>e.source==='cowrie'&&e.ip==='192.168.1.71').length),1);
    await page.uncheck('#demo-source-cowrie');
    await page.getByRole('button',{name:'Salva impostazioni demo',exact:true}).click();
    await page.getByRole('button',{name:'Simula tentativo fallito',exact:true}).click();
    assert.match(await page.locator('#demo-credential-status').textContent(),/Abilita Cowrie/);
    await page.getByRole('button',{name:'Ripristina valori iniziali',exact:true}).click();
    assert.equal(await page.locator('#threshold-login').inputValue(),'3');
    const correlation=await page.evaluate(()=>{
      const reference=demoEvents.find(e=>e.id===103), candidate={...reference,id:999,timestamp:new Date().toISOString()};
      const withSession=addDemoIncident(candidate);
      demoSettings.post_login_dedupe_by_session=false;
      const withoutSession=addDemoIncident(candidate);
      if(withoutSession)demoEvents.splice(demoEvents.indexOf(candidate),1);
      demoSettings.post_login_dedupe_by_session=true;
      return {withSession,withoutSession};
    });
    assert.deepEqual(correlation,{withSession:false,withoutSession:true});
    console.log('OK storyline, sorgenti, soglia operativa, disabilitazione, reset e deduplicazione sessioni');

    await page.evaluate(()=>switchPanel('export'));
    const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'↓ Scarica JSON',exact:true}).click()]);
    const report=JSON.parse(await fs.readFile(await download.path(),'utf8'));
    assert.equal(report.dataMode,'SIMULATED_FRONTEND');
    assert.equal(report.metrics.incidents,Number(await page.locator('#demo-total').textContent()));
    assert.equal(report.events.length,report.metrics.incidents);
    assert.equal(report.events.some(e=>e.id===104),false);
    await page.evaluate(()=>openDemoIncident(104));
    const [detailDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'↓ Report HTML',exact:true}).click()]);
    const detailReport=await fs.readFile(await detailDownload.path(),'utf8');
    assert.match(detailReport,/#104/);assert.match(detailReport,/authorized_activity/);
    assert.ok(!detailReport.includes('<script>'));
    await page.evaluate(()=>closeDemoDetail());
    console.log('OK export JSON filtrato e report HTML del singolo incidente');

    await page.evaluate(()=>{resetDemoFilters();switchPanel('overview');});
    const before=await page.evaluate(()=>demoEvents.length);
    await page.getByRole('button',{name:'▶ Riproduci scenario',exact:true}).click();
    await page.waitForFunction(()=>demoPlaybackIndex===1);
    assert.equal(await page.evaluate(()=>demoEvents.length),before+1);
    await page.getByRole('button',{name:'Ⅱ Pausa scenario',exact:true}).click();
    const paused=await page.evaluate(()=>demoPlaybackIndex);
    await page.waitForTimeout(3200);
    assert.equal(await page.evaluate(()=>demoPlaybackIndex),paused);
    assert.equal(await page.locator('#demo-total').textContent(),String(report.metrics.incidents+1));
    console.log('OK riproduzione deterministica, pausa e coerenza contatori');

    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'/tmp/hpx-site-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(300);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.locator('.dash-page-nav [data-panel="thresholds"]').click();
    assert.equal(await page.locator('#panel-thresholds').isVisible(),true);
    await page.locator('.dash-page-nav [data-panel="overview"]').click();
    await page.screenshot({path:'/tmp/hpx-site-mobile.png',fullPage:true});
    await page.evaluate(()=>navigateTo('home'));
    await page.waitForSelector('#page-home.active');
    assert.equal(await page.locator('#page-dashboard').isVisible(),false);
    assert.deepEqual(errors,[]);assert.deepEqual(productionRequests,[]);
    console.log('OK responsive, navigazione mobile, ritorno home, nessun errore JS o accesso API produzione');
    const offline=await browser.newPage({viewport:{width:1024,height:800}});
    const offlineErrors=[];offline.on('pageerror',error=>offlineErrors.push(error.message));
    await offline.route('**/leaflet@*/**',route=>route.abort());
    await offline.goto(process.env.HPX_DEMO_URL||'http://127.0.0.1:8765/',{waitUntil:'networkidle'});
    await offline.evaluate(()=>navigateTo('dashboard'));
    await offline.waitForSelector('#panel-overview.active');
    await offline.waitForFunction(()=>document.getElementById('demo-map').textContent.includes('Cartografia non disponibile'));
    assert.equal(await offline.locator('#demo-total').textContent(),'11');
    await offline.evaluate(()=>switchPanel('events'));
    assert.equal(await offline.locator('#demo-events tbody tr').count(),11);
    assert.deepEqual(offlineErrors,[]);
    await offline.close();
    console.log('OK CDN Leaflet indisponibile: incidenti e navigazione restano funzionanti');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
